def purpose(name, category):
    lowered = (name or '').lower()
    for words, text in PURPOSE:
        if all(word in lowered for word in words):
            return text
    return FALLBACK.get(category, '')


def headline(name):
    """The part of the name that says what the product is."""
    plain = (name or '').replace('\xa0', ' ')
    # A few names open with the range instead of the product: «(1...10 бар) Реле давления»
    plain = re.sub(r'^\s*\([^)]*\)\s*', '', plain)
    head = re.split(r'[,(]', plain)[0].strip()
    head = re.sub(r'\s+', ' ', head).strip(' -–—')
    if len(head) < 6:
        head = re.sub(r'\s+', ' ', (name or '')).strip()
    return head[:1].upper() + head[1:] if head else ''


def parameters(pairs):
    """The parameters as one readable sentence."""
    values = dict(pairs)
    parts = []

    body = values.pop('Материал корпуса', None)
    collet = values.pop('Материал цанги', None)
    for label, value in pairs:
        if label in ('Материал корпуса', 'Материал цанги'):
            continue
        if label == 'Материал':
            parts.append(f'материал — {value}')
        elif label in PHRASES:
            parts.append(PHRASES[label].format(value))

    material = []
    if body and collet and body.lower() == collet.lower():
        material.append(f'корпус и цанга — {body}')
    else:
        if body:
            material.append(f'корпус — {body}')
        if collet:
            material.append(f'цанга — {collet}')

    # Materials read better at the end, next to the weight
    weight = [part for part in parts if part.startswith('вес ')]
    parts = [part for part in parts if not part.startswith('вес ')]
    parts = parts + material + weight

    return ', '.join(parts)


def describe(name, category, sku=None, weight=None):
    sentences = [s for s in (f'{headline(name)}.', purpose(name, category)) if s.strip(' .')]

    numbers = parameters(specifications(name, weight))
    if numbers:
        sentences.append(f'{numbers[:1].upper()}{numbers[1:]}.')
    if sku:
        sentences.append(f'Артикул {sku}.')

    return ' '.join(sentences)


def fill_column(source, target, name_col=1, sku_col=2, category_col=3,
                weight_col=8, description_col=9):
    """Copy a catalogue file, writing a description for every row."""
    import openpyxl
    from openpyxl.styles import Alignment

    book = openpyxl.load_workbook(source)
    sheet = book.active

    written = 0
    for row in range(2, sheet.max_row + 1):
        text = describe(
            sheet.cell(row=row, column=name_col).value,
            sheet.cell(row=row, column=category_col).value,
            sheet.cell(row=row, column=sku_col).value,
            sheet.cell(row=row, column=weight_col).value,
        )
        cell = sheet.cell(row=row, column=description_col, value=text)
        cell.alignment = Alignment(wrap_text=True, vertical='top')
        written += bool(text)

    sheet.column_dimensions[
        openpyxl.utils.get_column_letter(description_col)].width = 70
    book.save(target)
    return sheet.max_row - 1, written


